drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
  for select to authenticated
  using (id = auth.uid());

drop policy if exists "profiles_insert_own_safe" on public.profiles;
create policy "profiles_insert_own_safe" on public.profiles
  for insert to authenticated
  with check (
    id = auth.uid()
    and coalesce(is_subscribed, false) = false
    and coalesce(plan, 'free') = 'free'
    and coalesce(subscription_status, 'inactive') = 'inactive'
    and subscription_provider is null
    and subscription_customer_id is null
    and subscription_id is null
  );

drop policy if exists "profiles_update_own_non_subscription" on public.profiles;
create policy "profiles_update_own_non_subscription" on public.profiles
  for update to authenticated
  using (id = auth.uid())
  with check (
    id = auth.uid()
    and is_subscribed = false
    and plan = 'free'
    and subscription_status = 'inactive'
    and subscription_provider is null
    and subscription_customer_id is null
    and subscription_id is null
  );

