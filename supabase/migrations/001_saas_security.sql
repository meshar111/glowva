-- Glowva SaaS baseline schema, RLS, analytics views, usage limits, and payment-safe subscriptions.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  plan text not null default 'free',
  is_subscribed boolean not null default false,
  subscription_status text not null default 'inactive',
  subscription_provider text,
  subscription_customer_id text,
  subscription_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_plan_check check (plan in ('free', 'monthly', 'yearly', 'enterprise')),
  constraint profiles_subscription_status_check check (subscription_status in ('inactive', 'trialing', 'active', 'past_due', 'canceled'))
);

create table if not exists public.visits (
  id bigint generated by default as identity primary key,
  country text,
  city text,
  path text,
  user_agent text,
  created_at timestamptz not null default now()
);

create table if not exists public.searches (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  product_name text,
  query text,
  country text,
  city text,
  result jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.usage_events (
  id bigint generated by default as identity primary key,
  event_type text not null,
  actor_type text not null,
  actor_id text not null,
  ip text,
  created_at timestamptz not null default now(),
  constraint usage_events_actor_type_check check (actor_type in ('ip', 'user', 'email'))
);

create index if not exists usage_events_actor_window_idx
  on public.usage_events (event_type, actor_type, actor_id, created_at desc);

create table if not exists public.usage_counters (
  event_type text not null,
  actor_type text not null,
  actor_id text not null,
  window_start timestamptz not null,
  count int not null default 0,
  updated_at timestamptz not null default now(),
  primary key (event_type, actor_type, actor_id, window_start),
  constraint usage_counters_actor_type_check check (actor_type in ('ip', 'user', 'email'))
);

create table if not exists public.analysis_cache (
  cache_key text primary key,
  result jsonb not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists analysis_cache_expires_at_idx on public.analysis_cache (expires_at);

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  provider text not null,
  event_id text not null,
  event_type text not null,
  payload jsonb not null,
  processed_at timestamptz not null default now(),
  unique (provider, event_id)
);

